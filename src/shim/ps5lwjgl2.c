// ps5lwjgl2.c: the hand-written natives of the LWJGL 2 compatibility layer (Minecraft 1.12.2 and older), built by build_lwjgl2.sh.
// LWJGL 2's own Java classes (built from its sources) call natives in three groups:
//   * generated GL / AL stubs + common_tools.c etc. from LWJGL 2's sources: compiled as they are (build_lwjgl2.sh)
//   * PS5Display / PS5ContextImplementation / GLContext / DefaultSysImplementation / AL loading: below. They sit on the GLFW shim of ps5lwjgl.c (window, EGL context,
//     pad -> keyboard/mouse) and on the software OpenAL (ps5al.inc), both reached through their public names, so this file also builds against a test shim (tests/lw2_test.c)
//   * JNI_OnLoad_lwjgl2ps5: registers every native with RegisterNatives (table generated by build_lwjgl2.sh). LWJGL 2 and LWJGL 3 use the SAME JNI names for different
//     functions (Java_org_lwjgl_opengl_GL11_nglClear ...), so by-name lookup cannot serve both; all LWJGL 2 symbols are renamed l2_* and bound by this table.
