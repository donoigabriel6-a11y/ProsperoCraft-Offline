#!/bin/bash
# gen_symtab.sh <sdk> <libdir> <out.c>: symbol table for the JDK native libraries (replaces dlsym).
set -e
S=$1; L=$2; OUT=$3; LW=${4:-$L}   # LW: directory of liblwjgl_ps5.a (the LWJGL natives are built once, next to the primary JDK)
NM=$S/bin/llvm-nm
SYMS=$({ for a in java zip net nio jimage verify management management_ext sunec; do $NM -g --defined-only $L/lib$a.a 2>/dev/null; done; $NM -g --defined-only $LW/liblwjgl_ps5.a 2>/dev/null; } \
  | awk 'NF==3 && ($2=="T"||$2=="D"||$2=="B"||$2=="R"||$2=="W"){print $3}' \
  | grep -E '^(Java_|JNI_OnLoad_|JNI_OnUnload_|JIMAGE_|ZIP_|JDK_|JNU_|Inflate|VerifyClass|GetStringPlatformChars|getErrorString)|^(Canonicalize|NewStringPlatform)$' | LC_ALL=C sort -u)   # Canonicalize: Java 8's libjava entry the VM looks up for class path entries
{
  echo "/* generated by gen_symtab.sh: do not edit */"
  echo "struct Ps5Sym { const char *name; void *addr; };"
  for s in $SYMS; do echo "extern char $s[];"; done
  echo "const struct Ps5Sym ps5_symtab[] = {"
  for s in $SYMS; do echo "  { \"$s\", (void *)$s },"; done
  echo "};"
  echo "const int ps5_symtab_n = $(echo "$SYMS" | wc -l);"
} > $OUT
echo "symtab: $(echo "$SYMS" | wc -l) symbols"
